/**
 * One automatic reconnect per network change burst. A phone rejoining a hotspot
 * fires `online` and `change` several times in a second, and a reconnect storm
 * would tear down a signaling engine that is still settling.
 */
const NETWORK_RECOVERY_COOLDOWN_MS = 5000

export function useGhostRoom(options: UseGhostRoomOptions = {}): GhostRoom {
  const requestedRaw = options.roomCode?.trim() ?? ''
  const requestedCode = requestedRaw.length > 0 ? normalizeRoomCode(requestedRaw) : ''
  const requestedRole = options.role
  const isGuest =
    requestedRole === 'peer'
      ? true
      : requestedRole === 'host'
        ? false
        : requestedCode.length > 0 && isValidRoomCode(requestedCode)
  const registerUnloadHooks = options.registerUnloadHooks !== false
  const autoConnect = options.autoConnect !== false

  const session = useMemo<{ roomCode: string | null; role: PeerRole }>(() => {
    if (isGuest) {
      return { roomCode: requestedCode.length > 0 ? requestedCode : null, role: 'peer' }
    }
    if (requestedCode.length > 0 && isValidRoomCode(requestedCode)) {
      return { roomCode: requestedCode, role: 'host' }
    }
    return { roomCode: safeGenerateRoomCode(), role: 'host' }
  }, [isGuest, requestedCode])

  // One store per room lifecycle. It is replaced when the room code changes and
  // disposed on room change and on unmount, so a stale room can never keep an
  // object URL alive. A disposed store is always replaced, never reused.
  const storeKey = session.roomCode ?? 'no-room'
  const storeRef = useRef<{ key: string; store: EphemeralStore } | null>(null)
  if (
    storeRef.current === null ||
    storeRef.current.key !== storeKey ||
    storeRef.current.store.isDisposed()
  ) {
    storeRef.current = { key: storeKey, store: new EphemeralStore({ registerUnloadHooks }) }
  }
  const store = storeRef.current.store

  /**
   * Detected once per mount. Every label, chip, badge and bridge icon on this
   * screen reads these two values instead of a hardcoded device name.
   */
  const localDeviceType = useMemo<DeviceType>(() => detectDeviceType(), [])
  const localDeviceName = useMemo(() => localSelfLabel(localDeviceType), [localDeviceType])

  const engineRef = useRef<PeerJsEngine | null>(null)
  const offlineEngineRef = useRef<OfflineDirectEngine | null>(null)
  /** Unsubscribes every listener of the offline engine that is live right now. */
  const offlineDetachRef = useRef<(() => void) | null>(null)
  /** Room and role the offline engine was built for, so a stale one is replaced. */
  const offlineKeyRef = useRef('')

  /**
   * Whichever transport actually holds a peer wins. Sending, burning and saving
   * therefore behave identically over the online engine and the offline engine.
   */
  const activeEngine = useCallback((): P2PSignalingAdapter | null => {
    const offline = offlineEngineRef.current
    if (offline && offline.peers.length > 0) return offline

    const online = engineRef.current
    if (online && online.peers.length > 0) return online

    return online ?? offline
  }, [])

  /**
   * StrictMode runs effect cleanup before the real mount, so disposal is
   * deferred by one task and cancelled when the same store reattaches. A real
   * unmount always reaches zero pending mounts, so nothing survives it.
   */
  const disposeTimersRef = useRef(new Map<EphemeralStore, ReturnType<typeof setTimeout>>())
  useEffect(() => {
    const pending = disposeTimersRef.current.get(store)
    if (pending !== undefined) {
      clearTimeout(pending)
      disposeTimersRef.current.delete(store)
    }

    return () => {
      const timer = setTimeout(() => {
        disposeTimersRef.current.delete(store)
        store.dispose()
      }, 0)
      disposeTimersRef.current.set(store, timer)
    }
  }, [store])

  const [status, setStatus] = useState<GhostRoomStatus>('idle')
  const [peers, setPeers] = useState<readonly PeerInfo[]>([])
  const [feedback, setFeedback] = useState<RoomFeedback | null>(null)
  const [connectionError, setConnectionError] = useState<RoomFeedbackKey | null>(null)
  const [ttlPreset, setTtlPresetState] = useState<TtlPreset>('50m')
  const [installedHint, setInstalledHint] = useState(false)
  const [progress, setProgress] = useState<Record<string, number>>({})
  /**
   * Every engine rebuild increments this nonce, so one manual reconnect or one
   * scheduled guest rejoin replaces the signaling engine without touching the
   * store, the feed or the transfer history.
   */
  const [reconnectNonce, setReconnectNonce] = useState(0)
  const [reconnectAttempt, setReconnectAttempt] = useState(0)
  /** Survives the engine effect so the backoff budget is never restarted early. */
  const reconnectAttemptsRef = useRef(0)

  const sendMetaRef = useRef(new Map<string, SendMeta>())
  const namesRef = useRef(new Map<string, string>())
  const warnedRef = useRef(new Set<string>())
  const ttlPresetRef = useRef<TtlPreset>('50m')
  /** Last committed whole percent per item, so 16KB frames never thrash React. */
  const progressPercentRef = useRef(new Map<string, number>())
  /** Tracks room creation per mode so telemetry events are not double sent. */
  const trackedRoomCreatedRef = useRef<Set<string>>(new Set())
  /**
   * Async actions can resolve after their component is gone, so every state
   * write that follows an await is gated on this flag. It mirrors the `active`
   * flag the engine effect already uses.
   */
  const mountedRef = useRef(true)

  /* ---------------------------------------------------------------------- */
  /* Offline direct state                                                    */
  /* ---------------------------------------------------------------------- */

  const [isOfflineDirect, setIsOfflineDirect] = useState(false)
  const [offlineStep, setOfflineStep] = useState<OfflineHandshakeStep>('idle')
  const [offlineInviteToken, setOfflineInviteToken] = useState<string | null>(null)
  const [offlineReplyToken, setOfflineReplyToken] = useState<string | null>(null)

  /** Mirrors of the state above, for callbacks that outlive a render. */
  const isOfflineDirectRef = useRef(false)
  const offlineStepRef = useRef<OfflineHandshakeStep>('idle')
  const offlineInviteTokenRef = useRef<string | null>(null)
  /** True after an automatic failover, so a network change can retry the room. */
  const networkFailoverRef = useRef(false)
  /**
   * True while a direct link code is being built. A recovery signal that lands
   * mid-build is ignored, so the code the user is waiting on is never raced.
   */
  const offlineBuildRef = useRef(false)
  /**
   * Set by the room effect so a network change can retry cloud signaling in
   * place, without rebuilding the room and without touching the direct link.
   */
  const onlineRetryRef = useRef<(() => void) | null>(null)
  /** Guards a StrictMode double effect from overwriting a newer invite code. */
  const offerGenerationRef = useRef(0)
  /** One hash token per mount, so a repaint can never replay the handshake. */
  const consumedHashRef = useRef<string | null>(null)
  /** Live status and peers, for the network recovery listener. */
  const statusRef = useRef<GhostRoomStatus>('idle')
  const peersRef = useRef<readonly PeerInfo[]>([])

  useEffect(() => {
    statusRef.current = status
  }, [status])

  useEffect(() => {
    peersRef.current = peers
  }, [peers])

  /**
   * One receiver per store, shared by both engines. A file arriving over the
   * online link and a file arriving over the direct link is reassembled by the
   * exact same 16KB budget checks, and the ACK travels back on the engine that
   * actually received the chunks.
   */
  const receiverRef = useRef<{ store: EphemeralStore; receiver: ChunkReceiver } | null>(null)
  if (receiverRef.current === null || receiverRef.current.store !== store) {
    receiverRef.current = {
      store,
      receiver: new ChunkReceiver({
        send: (packet: WirePacket) => {
          activeEngine()?.send(packet)
        },
        onProgress: (payload) => {
          activeEngine()?.reportTransferProgress(payload)
        },
        onItem: (received) => {
          if (!mountedRef.current) return
          if (store.isDisposed() || store.hasItem(received.id)) return
          namesRef.current.set(received.id, received.name)
          store.addFile({
            id: received.id,
            file: received.blob,
            fileName: received.name,
            mime: received.mime,
            direction: 'received',
            ttlMs: received.ttlMs,
            burnOnCopy: received.burnOnRead,
          })
        },
        onError: () => {
          if (!mountedRef.current) return
          setFeedback(buildFeedback('ERR_CHUNK_INTERRUPTED'))
        },
      }),
    }
  }
  const receiver = receiverRef.current.receiver

  useEffect(() => {
    mountedRef.current = true
    return () => {
      mountedRef.current = false
    }
  }, [])

  useEffect(() => {
    ttlPresetRef.current = ttlPreset
  }, [ttlPreset])

  /**
   * One preset change writes the ref synchronously, so a drop sent in the same
   * tick already uses the new rule, then retimes every active item so a note or
   * file sent before the change adopts the new cleanup rule immediately.
   * Source: docs/tasks/step-10-v07-offline-hotspot-camera-ttl-and-ux/web-task.md item 5.4.
   */
  const applyTtlPreset = useCallback(
    (nextPreset: TtlPreset) => {
      ttlPresetRef.current = nextPreset
      setTtlPresetState(nextPreset)

      if (store.isDisposed()) return

      const burnOnCopy = nextPreset === 'BURN_ON_COPY'
      const ttlMs = ttlMsForPreset(nextPreset)
      const now = store.now()

      for (const item of store.getSnapshot()) {
        if (item.status === 'expired' || item.status === 'nuked' || item.status === 'error') continue
        const deleteAt = burnOnCopy || ttlMs === null ? null : now + ttlMs
        store.updateItem(item.id, { burnOnCopy, deleteAt })
      }
    },
    [store],
  )

  useEffect(() => {
    sendMetaRef.current.clear()
    namesRef.current.clear()
    warnedRef.current.clear()
    progressPercentRef.current.clear()
    reconnectAttemptsRef.current = 0
    setReconnectAttempt(0)
    setProgress({})
    setPeers([])
    setConnectionError(null)
    // A new room starts online: the offline cards only appear once the room
    // fails over or the user asks for a direct link.
    networkFailoverRef.current = false
    isOfflineDirectRef.current = false
    offlineStepRef.current = 'idle'
    offlineInviteTokenRef.current = null
    setIsOfflineDirect(false)
    setOfflineStep('idle')
    setOfflineInviteToken(null)
    setOfflineReplyToken(null)

    return () => {
      // A lost ACK leaves an entry behind, so stale send metadata is dropped
      // with the room and with the mount rather than accumulating.
      sendMetaRef.current.clear()
    }
  }, [session.roomCode])

  const dismissFeedback = useCallback(() => setFeedback(null), [])

  /** Mount-safe feedback write for the async action paths. */
  const announce = useCallback((next: RoomFeedback) => {
    if (mountedRef.current) setFeedback(next)
  }, [])

  /** Public door for UI copy actions, such as the hub room code copy. */
  const announceFeedback = useCallback(
    (key: RoomFeedbackKey) => {
      announce(buildFeedback(key))
    },
    [announce],
  )

  /**
   * Turns a wire progress event into a 0 to 1 value for the feed.
   * One whole percent step per commit keeps a fast 16KB stream from
   * re-rendering the page hundreds of times per file.
   */
  const publishProgress = useCallback((payload: TransferProgress) => {
    const total = payload.totalBytes
    const ratio = total > 0 ? payload.bytesTransferred / total : payload.percent / 100
    const clamped = Math.min(1, Math.max(0, ratio))
    const percent = Math.round(clamped * 100)

    if (progressPercentRef.current.get(payload.id) === percent) return
    progressPercentRef.current.set(payload.id, percent)

    if (!mountedRef.current) return
    setProgress((current) =>
      current[payload.id] === clamped ? current : { ...current, [payload.id]: clamped },
    )
  }, [])

  /* ---------------------------------------------------------------------- */
  /* Offline direct helpers                                                  */
  /* ---------------------------------------------------------------------- */

  const applyOfflineDirect = useCallback(
    (next: boolean) => {
      isOfflineDirectRef.current = next
      if (mountedRef.current) setIsOfflineDirect(next)
      if (next && session.roomCode) {
        const offlineKey = `${session.roomCode}:offline_direct`
        if (!trackedRoomCreatedRef.current.has(offlineKey)) {
          trackedRoomCreatedRef.current.add(offlineKey)
          trackRoomCreated('offline_direct')
        }
      }
    },
    [session.roomCode],
  )

  const applyOfflineStep = useCallback((next: OfflineHandshakeStep) => {
    offlineStepRef.current = next
    if (mountedRef.current) setOfflineStep(next)
  }, [])

  const applyOfflineInvite = useCallback((token: string | null) => {
    offlineInviteTokenRef.current = token
    if (mountedRef.current) setOfflineInviteToken(token)
  }, [])

  const applyOfflineReply = useCallback((token: string | null) => {
    if (mountedRef.current) setOfflineReplyToken(token)
  }, [])

  /** Identity every transport handshake announces over the wire. */
  const connectOptions = useMemo(
    () => ({
      roomCode: session.roomCode ?? '',
      role: session.role,
      deviceName: options.deviceName ?? deviceNameFor(localDeviceType),
      deviceType: localDeviceType,
    }),
    [session.roomCode, session.role, options.deviceName, localDeviceType],
  )

  /**
   * The single inbound packet handler. Both engines call this exact function,
   * so a note, a file header, an ACK and a burn notice behave identically on
   * the online link and the direct link.
   */
  const handleInboundPacket = useCallback(
    (packet: WirePacket, from: string) => {
      if (!mountedRef.current) return

      switch (packet.type) {
        case 'TEXT': {
          if (store.isDisposed() || store.hasItem(packet.id)) return
          namesRef.current.set(packet.id, 'that note')
          // The deadline is anchored to the local receipt clock, never to
          // packet.timestamp, so a sender with a skewed clock can neither
          // expire a note on arrival nor stretch it past the chosen preset.
          store.addText({
            id: packet.id,
            text: packet.text,
            direction: 'received',
            ttlMs: packet.ttlMs,
            burnOnCopy: packet.burnOnRead === true,
            peerId: from,
          })
          setFeedback(buildFeedback('SUCCESS_TEXT_RECEIVED'))
          return
        }
        case 'FILE_START':
        case 'FILE_CHUNK':
        case 'FILE_END':
          receiver.handlePacket(packet)
          return
        case 'FILE_ACK': {
          const meta = sendMetaRef.current.get(packet.id)
          // A relayed ACK for another device's file is not ours to settle.
          if (!meta) return
          sendMetaRef.current.delete(packet.id)

          if (packet.status === 'OK') {
            if (meta.dropAndNuke) {
              store.acknowledgeDelivery(packet.id)
              setFeedback(
                buildFeedback('SUCCESS_DROP_AND_NUKE', { fileName: meta.fileName }),
              )
            } else {
              store.updateItem(packet.id, { status: 'ready' })
              setFeedback(buildFeedback('SUCCESS_FILE_SENT', { fileName: meta.fileName }))
            }
          } else {
            store.updateItem(packet.id, { status: 'error' })
            setFeedback(buildFeedback('ERR_CHUNK_INTERRUPTED'))
          }
          return
        }
        case 'ITEM_NUKE': {
          // Read the name before removal so the poof notice can name the item.
          const nukedItem = store.getItem(packet.id)
          const nukedName = nukedItem ? itemNameFor(nukedItem) : namesRef.current.get(packet.id)
          const removed = store.removeItem(packet.id, packet.reason)
          if (removed) {
            sendMetaRef.current.delete(packet.id)
            namesRef.current.delete(packet.id)
            if (packet.reason === 'BURN_ON_COPY') {
              setFeedback(
                buildFeedback('INFO_TTL_EXPIRED', {
                  preset: 'BURN_ON_COPY',
                  itemName: nukedName ?? 'that item',
                }),
              )
            }
          }
          return
        }
        case 'HELLO_PEER':
          return
      }
    },
    [receiver, store],
  )

  const handleInboundBinary = useCallback(
    (data: ArrayBuffer) => {
      if (!mountedRef.current) return
      receiver.handleBinary(data)
    },
    [receiver],
  )

  /**
   * Wires one offline engine to the shared receiver, the shared packet handler
   * and the same playful feedback layer the online engine uses.
   */
  const wireOfflineEngine = useCallback(
    (engine: OfflineDirectEngine): (() => void) => {
      const detach: Array<() => void> = []

      detach.push(engine.on('packet', ({ packet, from }) => handleInboundPacket(packet, from)))
      detach.push(engine.on('binary', ({ data }) => handleInboundBinary(data)))
      detach.push(engine.on('transfer:progress', (payload) => publishProgress(payload)))

      detach.push(
        engine.on('peer:join', (peer) => {
          if (!mountedRef.current) return
          reconnectAttemptsRef.current = 0
          networkFailoverRef.current = false
          setReconnectAttempt(0)
          setPeers([...engine.peers])
          setConnectionError(null)
          setStatus('connected')
          applyOfflineDirect(true)
          applyOfflineStep('connected')
          // A same device link finishes without a scan, so the codes are
          // published from the engine once the channel is open.
          applyOfflineInvite(engine.hostInviteToken)
          applyOfflineReply(engine.guestReplyToken)
          setFeedback(buildFeedback('SUCCESS_PEER_JOINED'))
          trackPeerConnected(peer?.deviceType ?? localDeviceType)
        }),
      )

      detach.push(
        engine.on('peer:leave', () => {
          if (!mountedRef.current) return
          setPeers([])
          setConnectionError(null)
          // The direct link dropped, so this is never a dead end: the host waits
          // for a fresh reply and the guest can show its reply again.
          setStatus('connecting')
          if (session.role === 'host') {
            applyOfflineStep('host-waiting-for-reply')
          } else if (engine.guestReplyToken) {
            applyOfflineReply(engine.guestReplyToken)
            applyOfflineStep('guest-showing-reply')
          } else {
            applyOfflineStep('idle')
          }
          setFeedback(buildFeedback('ERR_PEER_DISCONNECTED'))
        }),
      )

      return () => {
        for (const off of detach) off()
      }
    },
    [
      applyOfflineDirect,
      applyOfflineInvite,
      applyOfflineReply,
      applyOfflineStep,
      handleInboundBinary,
      handleInboundPacket,
      publishProgress,
      session.role,
    ],
  )

  /**
   * Returns the offline engine for the current room, building it on demand.
   * Being lazy is what lets a scanned code be accepted from an effect that runs
   * before the room effect has had a chance to create the engine.
   */
  const ensureOfflineEngine = useCallback((): OfflineDirectEngine => {
    const key = `${session.roomCode ?? ''}|${session.role}`
    const existing = offlineEngineRef.current
    if (existing && offlineKeyRef.current === key) return existing

    if (existing) {
      offlineDetachRef.current?.()
      offlineDetachRef.current = null
      existing.destroy()
      offlineEngineRef.current = null
      offlineKeyRef.current = ''
    }

    const engine = new OfflineDirectEngine()
    offlineEngineRef.current = engine
    offlineKeyRef.current = key
    offlineDetachRef.current = wireOfflineEngine(engine)
    return engine
  }, [session.roomCode, session.role, wireOfflineEngine])

  /**
   * Accepts either a host invite code on the guest or a guest reply code on the
   * host. Never throws: a bad paste is one playful toast and a false result.
   */
  const acceptOfflineToken = useCallback(
    async (rawInput: string): Promise<boolean> => {
      const token = extractCompactTokenFromInput(rawInput)
      if (!token) {
        announceFeedback('ERR_OFFLINE_CODE_INVALID')
        return false
      }

      let payload
      try {
        payload = await decodeCompactSdp(token)
      } catch {
        announceFeedback('ERR_OFFLINE_CODE_INVALID')
        return false
      }

      if (!mountedRef.current) return false

      if (payload.t === 'o') {
        // The invite names the room that must be joined. A screen sitting in a
        // different room moves there first, and the next mount finishes the
        // handshake from memory.
        if (payload.r !== session.roomCode) {
          stashPendingOfflineOffer(token)
          navigate(`/join?room=${payload.r}`)
          return true
        }

        // Only a screen that joined as a guest can answer an invite.
        if (session.role === 'host') {
          announceFeedback('ERR_OFFLINE_CODE_INVALID')
          return false
        }

        const engine = ensureOfflineEngine()
        const wasOffline = isOfflineDirectRef.current
        // The reply code is being built, so a network retry waits its turn.
        offlineBuildRef.current = true
        try {
          applyOfflineDirect(true)
          const reply = await engine.acceptOfferAndCreateAnswer(token, connectOptions)
          if (!mountedRef.current) return true
          applyOfflineReply(reply)
          applyOfflineStep('guest-showing-reply')
          setStatus('connecting')
          setConnectionError(null)
          announceFeedback('INFO_OFFLINE_REPLY_READY')
          return true
        } catch {
          // A misread code never undoes an offline mode the user already had.
          if (!wasOffline) applyOfflineDirect(false)
          applyOfflineStep('idle')
          announceFeedback('ERR_OFFLINE_CODE_INVALID')
          return false
        } finally {
          offlineBuildRef.current = false
        }
      }

      // A reply code is only meaningful on the screen that offered the invite.
      if (session.role !== 'host') {
        announceFeedback('ERR_OFFLINE_CODE_INVALID')
        return false
      }

      const engine = ensureOfflineEngine()
      // The direct link is being joined, so a network retry waits its turn.
      offlineBuildRef.current = true
      try {
        applyOfflineDirect(true)
        await engine.acceptAnswerToken(token)
        if (!mountedRef.current) return true
        applyOfflineStep('connected')
        setStatus('connected')
        setConnectionError(null)
        return true
      } catch {
        announceFeedback('ERR_OFFLINE_CODE_INVALID')
        return false
      } finally {
        offlineBuildRef.current = false
      }
    },
    [announceFeedback, applyOfflineDirect, applyOfflineReply, applyOfflineStep, connectOptions, ensureOfflineEngine, session.role, session.roomCode],
  )

  /**
   * Manual switch to the serverless link. Idempotent, so a double tap, a flaky
   * hotspot and a failed automatic failover can all call it safely.
   */
  const activateOfflineDirect = useCallback(async (): Promise<void> => {
    applyOfflineDirect(true)
    setConnectionError(null)
    setStatus((current) => (current === 'connected' ? current : 'connecting'))

    if (session.role === 'host') {
      if (offlineStep !== 'connected') applyOfflineStep('host-waiting-for-reply')

      // The invite is generated in the background on mount, but a browser that
      // refused it there gets one more chance on demand.
      if (!offlineInviteTokenRef.current && session.roomCode) {
        const engine = ensureOfflineEngine()
        // The invite code is being built, so a network retry waits its turn.
        offlineBuildRef.current = true
        try {
          const token = await engine.startHostOffer(connectOptions)
          if (mountedRef.current) applyOfflineInvite(token)
        } catch {
          // The card keeps its own retry, and online mode is untouched.
        } finally {
          offlineBuildRef.current = false
        }
      }
    }

    announceFeedback('INFO_OFFLINE_READY')
  }, [
    announceFeedback,
    applyOfflineDirect,
    applyOfflineInvite,
    applyOfflineStep,
    connectOptions,
    ensureOfflineEngine,
    offlineStep,
    session.role,
    session.roomCode,
  ])

  const handleExpire = useCallback((expiredIds: readonly string[]) => {
    const firstId = expiredIds[0]
    if (!firstId) return
    const itemName = namesRef.current.get(firstId)
    for (const id of expiredIds) namesRef.current.delete(id)
    setFeedback(
      buildFeedback('INFO_TTL_EXPIRED', {
        preset: ttlPresetRef.current,
        ...(itemName ? { itemName } : {}),
      }),
    )
  }, [])

  const { items, now, remainingMs } = useTtlJanitor({ store, onExpire: handleExpire })

  // Warn once per item inside the last minute so nothing vanishes unannounced.
  useEffect(() => {
    if (warnedRef.current.size > MAX_WARNED_IDS) warnedRef.current.clear()

    for (const item of items) {
      const remaining = getRemainingMs(item, now)
      if (remaining === null || remaining <= 0 || remaining > WARN_WINDOW_MS) continue
      if (warnedRef.current.has(item.id)) continue

      warnedRef.current.add(item.id)
      const itemName = namesRef.current.get(item.id) ?? item.fileName
      setFeedback(
        buildFeedback('WARN_TTL_EXPIRING_SOON', itemName ? { itemName } : undefined),
      )
      break
    }
  }, [items, now])

  useEffect(() => {
    if (typeof window === 'undefined') return

    const standaloneQuery = window.matchMedia('(display-mode: standalone)')
    const navigatorWithStandalone = window.navigator as Navigator & { standalone?: boolean }

    const update = () => {
      setInstalledHint(standaloneQuery.matches || navigatorWithStandalone.standalone === true)
    }

    update()
    standaloneQuery.addEventListener('change', update)
    return () => standaloneQuery.removeEventListener('change', update)
  }, [])

  // One signaling engine per room. Everything it raises is mapped to a copy deck
  // key before it can reach a component.
  useEffect(() => {
    if (!autoConnect) return

    if (!session.roomCode) {
      setStatus('error')
      setConnectionError('ERR_ROOM_NOT_FOUND')
      setFeedback(buildFeedback('ERR_ROOM_NOT_FOUND'))
      return
    }

    const roomCode = session.roomCode
    const role = session.role
    let active = true
    let rejoinTimer: ReturnType<typeof setTimeout> | null = null

    const clearRejoinTimer = () => {
      if (rejoinTimer === null) return
      clearTimeout(rejoinTimer)
      rejoinTimer = null
    }

    /** True while the guest still has one scheduled rejoin left in the budget. */
    const hasRejoinBudget = (): boolean =>
      REJOIN_DELAYS_MS[reconnectAttemptsRef.current] !== undefined

    /**
     * Guest rejoin. The engine is rebuilt through the nonce, so the signaling id
     * is fresh while the store and the feed keep every item that already landed.
     * Locked schedule: 900ms, 1800ms, 2700ms, 3600ms, then stop.
     */
    const scheduleRejoin = (): boolean => {
      const delay = REJOIN_DELAYS_MS[reconnectAttemptsRef.current]
      if (delay === undefined) return false

      reconnectAttemptsRef.current += 1
      setReconnectAttempt(reconnectAttemptsRef.current)
      setStatus('reconnecting')
      clearRejoinTimer()
      rejoinTimer = setTimeout(() => {
        rejoinTimer = null
        if (!active) return
        setReconnectNonce((current) => current + 1)
      }, delay)
      return true
    }

    /**
     * Offline failover. No internet signaling answered in time, so the
     * serverless direct link takes over instead of a dead end card: the status
     * stays "connecting", the offline codes become the way in, and the page
     * offers the direct link action.
     */
    const failoverToOffline = (key: RoomFeedbackKey) => {
      networkFailoverRef.current = true
      applyOfflineDirect(true)
      setConnectionError(key)
      setStatus('connecting')
      // A handshake that is already running owns the step, so the guest keeps
      // showing its reply code and a host that is already waiting stays waiting.
      if (role === 'host' && offlineStepRef.current === 'idle') {
        applyOfflineStep('host-waiting-for-reply')
      }
      setFeedback(buildFeedback(key, { roomCode: roomCode ?? undefined }))
    }

    const engine = new PeerJsEngine()
    engineRef.current = engine

    const cloudKey = `${roomCode}:cloud`
    if (!trackedRoomCreatedRef.current.has(cloudKey)) {
      trackedRoomCreatedRef.current.add(cloudKey)
      trackRoomCreated('cloud')
    }

    /**
     * The serverless engine is prepared in parallel on every room. A host
     * pre-generates its invite so the pairing QR already carries the offline
     * code, and a guest opens the same room channel so two tabs of one browser
     * can link with no scan at all.
     */
    const offline = ensureOfflineEngine()

    /**
     * Cloud signaling retry that leaves the direct link alone. The offline
     * engine, its room channel, the invite code and the reply code all keep
     * running, so a code already on screen stays valid while the room quietly
     * tries the online route again. Called by the network recovery listener.
     */
    const retryOnlineInPlace = () => {
      if (!active) return
      // An open direct link is never replaced by a late online one, and a code
      // that is still being built is never raced.
      if (offline.peers.length > 0 || offlineStepRef.current === 'connected') return
      if (offlineBuildRef.current) return
      // Cloud signaling is already back, so there is nothing to retry.
      if (engine.peers.length > 0) return

      // The waiting card stays up either way: the retry raises nothing itself,
      // and a failed attempt leaves the room on the direct link.
      setConnectionError(null)
      setStatus('connecting')

      void engine
        .connect({
          roomCode,
          role,
          deviceName: options.deviceName ?? deviceNameFor(localDeviceType),
          deviceType: localDeviceType,
        })
        .then(() => {
          if (!active) return
          networkFailoverRef.current = false
          setStatus('connected')
          setPeers([...engine.peers])
          setConnectionError(null)
          // The room is online again, so the direct link cards stand down and
          // nothing stale stays mounted. The codes and the offline engine are
          // kept ready in case the online route drops once more.
          applyOfflineDirect(false)
          applyOfflineStep('idle')
        })
        .catch(() => {
          // Still offline. Every direct link value is untouched, and the status
          // listener above keeps the room on the direct link.
        })
    }
    onlineRetryRef.current = retryOnlineInPlace

    const unsubscribePacket = engine.on('packet', ({ packet, from }) => {
      if (!active) return
      handleInboundPacket(packet, from)
    })

    const unsubscribeBinary = engine.on('binary', ({ data }) => {
      if (!active) return
      handleInboundBinary(data)
    })

    // Every byte count travels through the engine event bus, so the feed and
    // any future surface read the same progress source.
    const unsubscribeProgress = engine.on('transfer:progress', (payload) => {
      if (!active) return
      publishProgress(payload)
    })

    const unsubscribeStatus = engine.on('status', ({ status: engineStatus }) => {
      if (!active) return
      if (engineStatus === 'connecting') setStatus('connecting')
      else if (engineStatus === 'connected') setStatus('connected')
      else if (engineStatus === 'reconnecting') setStatus('reconnecting')
      else if (engineStatus === 'disconnected') {
        // A queued guest rejoin already owns the label, so no dead end flashes.
        if (role === 'peer' && reconnectAttemptsRef.current > 0 && hasRejoinBudget()) return
        // A dropped online link is not the end of the room: the direct link is
        // still available, so the offline cards take over.
        failoverToOffline('ERR_PEER_DISCONNECTED')
      }
    })

    const unsubscribeJoin = engine.on('peer:join', (peer) => {
      if (!active) return
      clearRejoinTimer()
      reconnectAttemptsRef.current = 0
      setReconnectAttempt(0)
      setPeers([...engine.peers])
      setConnectionError(null)
      setStatus('connected')
      setFeedback(buildFeedback('SUCCESS_PEER_JOINED'))
      trackPeerConnected(peer?.deviceType ?? localDeviceType)
    })

    const unsubscribeLeave = engine.on('peer:leave', () => {
      if (!active) return

      if (role === 'host') {
        // The host stays on the air for the next screen, so a screen leaving is
        // a short notice, never a blocking failure.
        setPeers([...engine.peers])
        setStatus('connecting')
        setConnectionError(null)
        setFeedback(buildFeedback('ERR_PEER_DISCONNECTED'))
        return
      }

      setPeers([])
      setConnectionError(null)
      if (scheduleRejoin()) return
      failoverToOffline('ERR_PEER_DISCONNECTED')
    })

    const unsubscribeError = engine.on('error', ({ code }) => {
      if (!active) return
      const key = feedbackKeyForError(code, role)
      if (isConnectionFailure(code)) {
        // A guest with a queued retry stays quiet until the budget is spent.
        if (role === 'peer' && reconnectAttemptsRef.current > 0 && hasRejoinBudget()) return
        // An already linked room keeps its link; only the notice changes.
        if (statusRef.current === 'connected') {
          setConnectionError(key)
          setFeedback(buildFeedback(key, { roomCode: roomCode ?? undefined }))
          return
        }
        failoverToOffline(key)
        return
      }
      setFeedback(buildFeedback(key, { roomCode: roomCode ?? undefined }))
    })

    const deviceType = localDeviceType
    // A rebuild during a rejoin keeps saying Reconnecting instead of blinking
    // back to Linking up between attempts.
    setStatus((current) => (current === 'reconnecting' ? current : 'connecting'))
    setConnectionError(null)

    if (role === 'host') {
      // One pre-generation per mount, and a StrictMode replay can never publish
      // a stale invite code over a newer one.
      offerGenerationRef.current += 1
      const generation = offerGenerationRef.current
      // The invite code is being built, so a network retry waits its turn.
      offlineBuildRef.current = true
      void offline
        .startHostOffer({
          roomCode,
          role,
          deviceName: options.deviceName ?? deviceNameFor(deviceType),
          deviceType,
        })
        .then((token) => {
          if (!active || !mountedRef.current) return
          if (offerGenerationRef.current !== generation) return
          applyOfflineInvite(token)
        })
        .catch(() => {
          // A browser that cannot gather an offer must never break online mode.
        })
        .finally(() => {
          offlineBuildRef.current = false
        })
    } else {
      void offline
        .connect({
          roomCode,
          role,
          deviceName: options.deviceName ?? deviceNameFor(deviceType),
          deviceType,
        })
        .catch(() => {
          // The room channel is a bonus, the scan and paste paths still work.
        })
    }

    void engine
      .connect({
        roomCode,
        role,
        deviceName: options.deviceName ?? deviceNameFor(deviceType),
        deviceType,
      })
      .then(() => {
        if (!active) return
        networkFailoverRef.current = false
        setStatus('connected')
        setPeers([...engine.peers])
      })
      .catch((error: unknown) => {
        if (!active) return
        const key = feedbackKeyForError(isP2PError(error) ? error.code : 'SIGNALING_ERROR', role)
        if (role === 'peer' && reconnectAttemptsRef.current > 0) {
          // The host may still be coming back, so spend the budget first.
          if (scheduleRejoin()) return
        }
        // Cloud signaling is unreachable, which is normal on a Wi-Fi router with
        // no internet or a hotspot with mobile data off, so the direct link
        // takes over instead of a dead end.
        failoverToOffline(key)
      })

    return () => {
      active = false
      onlineRetryRef.current = null
      clearRejoinTimer()
      unsubscribePacket()
      unsubscribeBinary()
      unsubscribeStatus()
      unsubscribeJoin()
      unsubscribeLeave()
      unsubscribeError()
      unsubscribeProgress()
      receiver.disposeAll()
      engine.destroy()
      if (engineRef.current === engine) engineRef.current = null

      if (offlineEngineRef.current === offline) {
        offlineDetachRef.current?.()
        offlineDetachRef.current = null
        offline.destroy()
        offlineEngineRef.current = null
        offlineKeyRef.current = ''
      }
    }
  }, [
    autoConnect,
    session.roomCode,
    session.role,
    store,
    options.deviceName,
    publishProgress,
    reconnectNonce,
    localDeviceType,
    applyOfflineDirect,
    applyOfflineInvite,
    applyOfflineStep,
    ensureOfflineEngine,
    handleInboundBinary,
    handleInboundPacket,
  ])

  /**
   * Every Reconnect action lands here: the budget starts over, the error card
   * clears, and the engine is rebuilt on the next effect pass. The store, the
   * feed and the auto-delete timers are untouched.
   */
  const reconnect = useCallback(() => {
    reconnectAttemptsRef.current = 0
    setReconnectAttempt(0)
    setConnectionError(null)
    setStatus('connecting')
    setReconnectNonce((current) => current + 1)
  }, [])

  /**
   * A code carried in the URL fragment, for example from a phone camera app
   * opening `/join?room=XXXXXX#gd=GD1...`.
   *
   * The fragment is cleared the instant it is read, so a reload or a back
   * navigation can never replay the handshake, and the token is remembered in a
   * ref so a repaint cannot run it twice. A StrictMode replay is covered by the
   * same ref because the second pass finds no fragment at all.
   */
  useEffect(() => {
    if (typeof window === 'undefined') return

    const consumeHash = () => {
      const token = extractCompactTokenFromInput(window.location.hash)
      if (!token) return
      if (consumedHashRef.current === token) return
      consumedHashRef.current = token

      window.history.replaceState(
        window.history.state,
        '',
        `${window.location.pathname}${window.location.search}`,
      )

      void acceptOfflineToken(token)
    }

    consumeHash()
    window.addEventListener('hashchange', consumeHash)
    return () => window.removeEventListener('hashchange', consumeHash)
  }, [acceptOfflineToken])

  /**
   * An invite that named another room moved this screen there, so the handshake
   * finishes on the room it belongs to. The stash is consumed exactly once.
   */
  useEffect(() => {
    const token = takePendingOfflineOffer()
    if (!token) return
    void acceptOfflineToken(token)
  }, [acceptOfflineToken])

  /**
   * Hands free recovery. Turning Wi-Fi or a hotspot back on after the cached app
   * opened with none of it retries the room on its own, with a cooldown so a
   * burst of `online` and `change` events never becomes a reconnect storm.
   *
   * A room waiting on a direct link code is retried in place rather than
   * rebuilt, so the invite code and the reply code stay on screen and stay
   * valid while cloud signaling is tried again. An open direct link is never
   * replaced, and a code that is still being built is never raced.
   */
  useEffect(() => {
    if (typeof window === 'undefined') return

    let lastAttempt = 0

    const tryRecover = () => {
      if (!mountedRef.current) return
      if (peersRef.current.length > 0) return
      if (offlineBuildRef.current) return

      const step = offlineStepRef.current
      const waitingOnOfflineCode =
        isOfflineDirectRef.current &&
        (step === 'host-waiting-for-reply' || step === 'guest-showing-reply')

      // A waiting direct link is a reason to retry on its own, because the room
      // is still reachable by code. Everything else keeps the original gate.
      if (
        statusRef.current !== 'error' &&
        !networkFailoverRef.current &&
        !waitingOnOfflineCode
      ) {
        return
      }
      // A connected direct link keeps running and is never torn down.
      if (isOfflineDirectRef.current && step === 'connected') return

      const at = Date.now()
      if (at - lastAttempt < NETWORK_RECOVERY_COOLDOWN_MS) return
      lastAttempt = at

      // A room already on the direct link retries signaling in place, so its
      // codes survive. Anything else gets a full engine rebuild.
      const retryInPlace = onlineRetryRef.current
      if (isOfflineDirectRef.current && retryInPlace) {
        retryInPlace()
        return
      }
      reconnect()
    }

    window.addEventListener('online', tryRecover)
    const network = (navigator as Navigator & { connection?: EventTarget }).connection
    network?.addEventListener('change', tryRecover)

    return () => {
      window.removeEventListener('online', tryRecover)
      network?.removeEventListener('change', tryRecover)
    }
  }, [reconnect])

  const sendText = useCallback(
    async (text: string): Promise<boolean> => {
      const value = text.trim()
      if (!value) return false

      const engine = activeEngine()
      if (!engine || store.isDisposed() || engine.peers.length === 0) {
        announce(buildFeedback('ERR_PEER_DISCONNECTED'))
        return false
      }

      const preset = ttlPresetRef.current
      const burnOnRead = preset === 'BURN_ON_COPY'
      const ttlMs = ttlMsForPreset(preset)
      const id = createItemId()

      try {
        engine.send({
          type: 'TEXT',
          id,
          text: value,
          timestamp: Date.now(),
          ttlMs,
          burnOnRead,
        })
        if (!store.hasItem(id)) {
          namesRef.current.set(id, 'that note')
          store.addText({ id, text: value, direction: 'sent', ttlMs, burnOnCopy: burnOnRead })
        }
        announce(buildFeedback('SUCCESS_TEXT_SENT'))
        return true
      } catch {
        announce(buildFeedback('ERR_CHUNK_INTERRUPTED'))
        return false
      }
    },
    [activeEngine, announce, store],
  )

  const sendFiles = useCallback(
    async (files: readonly File[], sendOptions: GhostSendOptions = {}): Promise<number> => {
      const engine = activeEngine()
      if (!engine || store.isDisposed()) {
        announce(buildFeedback('ERR_PEER_DISCONNECTED'))
        return 0
      }

      const transports: P2PTransport[] = []
      for (const peer of engine.peers) {
        const transport = engine.getTransport(peer.peerId)
        if (transport && transport.isOpen) transports.push(transport)
      }
      if (transports.length === 0) {
        announce(buildFeedback('ERR_PEER_DISCONNECTED'))
        return 0
      }

      const preset = ttlPresetRef.current
      const burnOnRead = preset === 'BURN_ON_COPY'
      const ttlMs = ttlMsForPreset(preset)
      const dropAndNuke = sendOptions.dropAndNuke === true
      let sent = 0
      let transferredBytes = 0

      for (const file of files) {
        const id = createItemId()

        try {
          namesRef.current.set(id, file.name)
          sendMetaRef.current.set(id, { fileName: file.name, dropAndNuke })
          store.addFile({
            id,
            file,
            fileName: file.name,
            mime: file.type,
            direction: 'sent',
            ttlMs,
            burnOnCopy: burnOnRead,
            status: 'sending',
          })

          const results = await Promise.allSettled(
            transports.map((connection) =>
              streamFile({
                connection,
                file,
                transferId: id,
                ttlMs,
                dropAndNuke,
                burnOnRead,
                name: file.name,
                mime: file.type,
                onProgress: (payload) => engine.reportTransferProgress(payload),
              }),
            ),
          )

          const everyTransportFailed = results.every((result) => result.status === 'rejected')
          if (everyTransportFailed) {
            sendMetaRef.current.delete(id)
            store.updateItem(id, { status: 'error' })
            announce(buildFeedback('ERR_CHUNK_INTERRUPTED'))
            continue
          }

          sent += 1
          transferredBytes += file.size
        } catch {
          sendMetaRef.current.delete(id)
          if (store.hasItem(id)) store.updateItem(id, { status: 'error' })
          announce(buildFeedback('ERR_CHUNK_INTERRUPTED'))
        }
      }

      if (sent > 0) {
        trackFileTeleported({
          count: sent,
          totalBytes: transferredBytes,
          ttl: preset,
        })
      }

      return sent
    },
    [activeEngine, announce, store],
  )

  /**
   * Burn on copy, synced. The store removal is local only, so the same instant
   * we also tell every connected screen to drop the item and show the same poof
   * confirmation. Without this the sender kept a dead copy on screen.
   * Source: docs/tasks/step-10-v07-offline-hotspot-camera-ttl-and-ux/web-task.md item 5.2.
   */
  const consumeAndSyncBurnOnCopy = useCallback(
    (id: string, itemName?: string): boolean => {
      const burned = store.consumeBurnOnCopy(id)
      if (!burned) return false

      sendMetaRef.current.delete(id)
      namesRef.current.delete(id)

      const engine = activeEngine()
      if (engine && engine.peers.length > 0) {
        try {
          engine.send({ type: 'ITEM_NUKE', id, reason: 'BURN_ON_COPY' })
        } catch {
          // The local copy is already gone, a lost notice never blocks the burn.
        }
      }

      announce(
        buildFeedback('INFO_TTL_EXPIRED', {
          preset: 'BURN_ON_COPY',
          itemName: itemName ?? 'that item',
        }),
      )
      return true
    },
    [activeEngine, announce, store],
  )

  /** Native OS share sheet for one note or file, then honours burn on copy. */
  const shareItem = useCallback(
    async (id: string): Promise<boolean> => {
      const item = store.getItem(id)
      if (!item) return false
      if (!canNativeShare()) return false

      try {
        if (item.kind === 'file') {
          const blob = await resolveItemBlob(item)
          if (!blob) return false

          const fileName = item.fileName ?? 'ghostdrop-file'
          const type = item.mime || blob.type || 'application/octet-stream'
          const file = new File([blob], fileName, { type })
          const data: ShareData = { files: [file], title: fileName }

          if (typeof navigator.canShare === 'function' && !navigator.canShare(data)) {
            return false
          }
          await navigator.share(data)
        } else if (item.kind === 'text' && typeof item.text === 'string') {
          await navigator.share({ text: item.text })
        } else {
          return false
        }
      } catch {
        // A dismissed share sheet is a normal outcome, never an error card.
        return false
      }

      if (!consumeAndSyncBurnOnCopy(id, itemNameFor(item))) {
        announce(buildFeedback('SUCCESS_SHARED'))
      }
      return true
    },
    [announce, consumeAndSyncBurnOnCopy, store],
  )

  /**
   * Copy to clipboard. Text uses `writeText` with an `execCommand` fallback for
   * plain HTTP LAN origins where `navigator.clipboard` is blocked, images go
   * through `ClipboardItem` after a PNG conversion, and a blocked write falls
   * back to the native share sheet before the playful retry card.
   */
  const copyItem = useCallback(
    async (id: string): Promise<boolean> => {
      const item = store.getItem(id)
      if (!item) return false

      let copied = false
      if (item.kind === 'text' && typeof item.text === 'string') {
        copied = await writeTextToClipboard(item.text)
      } else if ((item.mime ?? '').startsWith('image/')) {
        copied = await writeImageToClipboard(item)
      }

      if (!copied) {
        // A blocked clipboard still gets a joyful way out, never a silent tap.
        if (canNativeShare()) {
          const shared = await shareItem(id)
          if (shared) return true
        }
        announce(buildFeedback('ERR_CLIPBOARD_BLOCKED'))
        return false
      }

      if (!consumeAndSyncBurnOnCopy(id, itemNameFor(item))) {
        // A picture copy lands on the picture clipboard, so it says so.
        announce(buildFeedback(isImageItem(item) ? 'SUCCESS_COPIED_IMAGE' : 'SUCCESS_COPIED'))
      }
      return true
    },
    [announce, consumeAndSyncBurnOnCopy, shareItem, store],
  )

  /** Saves one received file or note. Burn on copy still dies on that first save. */
  const saveItem = useCallback(
    (id: string): boolean => {
      const item = store.getItem(id)
      if (!item) return false

      let saved = false
      if (item.blobUrl) {
        saved = triggerDownload(item.blobUrl, item.fileName ?? 'ghostdrop-file')
      } else if (item.kind === 'text' && typeof item.text === 'string') {
        saved = downloadTextNote(item.text, 'ghostdrop-note.txt')
      }

      if (!saved) {
        announce(buildFeedback('ERR_CHUNK_INTERRUPTED'))
        return false
      }

      if (!consumeAndSyncBurnOnCopy(id, itemNameFor(item))) {
        announce(buildFeedback('SUCCESS_SAVED', { fileName: itemNameFor(item) }))
      }
      return true
    },
    [announce, consumeAndSyncBurnOnCopy, store],
  )

  const burnItem = useCallback(
    (id: string): boolean => {
      if (!store.getItem(id)) return false
      const burned = store.burnNow(id)
      if (!burned) return false

      sendMetaRef.current.delete(id)
      namesRef.current.delete(id)

      const engine = activeEngine()
      if (engine && engine.peers.length > 0) {
        engine.send({ type: 'ITEM_NUKE', id, reason: 'MANUAL_BURN' })
      }
      return true
    },
    [activeEngine, store],
  )

  return {
    roomCode: session.roomCode,
    role: session.role,
    status,
    peers,
    items,
    now,
    progress,
    remainingMs,
    ttlPreset,
    setTtlPreset: applyTtlPreset,
    feedback,
    dismissFeedback,
    announceFeedback,
    connectionError,
    reconnect,
    reconnectAttempt,
    installedHint,
    sendText,
    sendFiles,
    copyItem,
    shareItem,
    saveItem,
    burnItem,
    localDeviceType,
    localDeviceName,
    isOfflineDirect,
    offlineStep,
    offlineInviteToken,
    offlineReplyToken,
    acceptOfflineToken,
    activateOfflineDirect,
  }
}
